# CALCULADORA EM PYTHON

# FUNÇÕES

def soma(numeros):
    resultado = 0
    contador = 0

    while contador < len(numeros):
        resultado += numeros[contador]
        contador += 1

    return resultado

def multiplicacao(numeros):
    resultado = 1
    contador = 0

    while contador < len(numeros):
        resultado *= numeros[contador]
        contador += 1

    return resultado

def divisao(numeros):
    resultado = numeros[0]
    contador = 1

    while contador < len(numeros):
        if numeros[contador] == 0:
            return "Erro: não é possível dividir por zero."

        resultado /= numeros[contador]
        contador += 1

    return resultado

def subtracao(numeros):
    resultado = numeros[0]
    contador = 1

    while contador < len(numeros):
        resultado -= numeros[contador]
        contador += 1

    return resultado

# FUNÇÃO PARA RECEBER NÚMEROS

def receber_numero():
    while True:
        try:
            numero = float(input("Digite um número: "))
            return numero
        except ValueError:
            print("Entrada inválida. Digite um número válido.")

# PROGRAMA PRINCIPAL

while True:

    numeros = []

    numero = receber_numero()
    numeros.append(numero)

    while True:
        continuar = input(
            "Deseja adicionar mais um número? (S/N): "
        ).lower()

        if continuar == "s":
            numero = receber_numero()
            numeros.append(numero)

        elif continuar == "n":
            break

        else:
            print("Opção inválida. Digite S ou N.")

    print(f"\nNúmeros digitados: {numeros}")

    print("\nQual operação deseja realizar?")
    print("1 - Soma")
    print("2 - Multiplicação")
    print("3 - Divisão")
    print("4 - Subtração")

    operacao = input("Digite o número da operação: ")

    if operacao == "1":
        resultado = soma(numeros)

    elif operacao == "2":
        resultado = multiplicacao(numeros)

    elif operacao == "3":
        resultado = divisao(numeros)

    elif operacao == "4":
        resultado = subtracao(numeros)

    else:
        resultado = "Operação inválida."

    print(f"\nResultado: {resultado}")

    novaoperacao = input(
        "\nDeseja fazer uma nova operação? (S/N): "
    ).lower()

    if novaoperacao == "n":
        print("Calculadora encerrada!")
        break